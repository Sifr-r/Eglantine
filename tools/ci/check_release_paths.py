"""Check Git paths and release archive member names for private emulator data."""

import argparse
from collections.abc import Iterable, Iterator
from pathlib import Path
import re
import sys
import tarfile
import zipfile
import zlib


PRIVATE_DIRECTORIES = {"ignore", ".lab"}
CONSOLE_KEYS = re.compile(r"(?:prod|dev|title|console)\.keys(?:_autogenerated)?|key_retail\.bin")
CONSOLE_CONTENT = re.compile(r"\.(?:nca|ncz|nsp|nsx|nsz|nup|xci|xcz)(?:\.[0-9]+)?$")
CAPTURE_NAMES = re.compile(
    r"(?:[0-9a-f]{16}-(?:gfx|cs)-[0-9a-f]+|rejected-[0-9a-f]+|native-inline-compute-shader)\.bin"
    r"|[0-9a-f]{16}_[0-9a-f]{16}\.spv"
    r"|.+\.(?:rdc|dmp|cubin)"
)


def rejection(parts: list[str], archive: bool) -> str | None:
    if any(part in {"", ".", ".."} for part in parts) or any(
        "\\" in part or "\0" in part or (archive and ":" in part) for part in parts
    ) or re.match(r"^[a-zA-Z]:", parts[0]):
        return "unsafe path"
    root_depth = 2 if archive else 1
    if any(part in PRIVATE_DIRECTORIES for part in parts[:root_depth]):
        return "private worktree path"
    if len(parts) <= root_depth + 1 and parts[-2:] == ["dist", "assets.car"]:
        return "quarantined asset"
    if archive and parts[-4:] == ["eglantine.app", "contents", "resources", "assets.car"]:
        return "quarantined asset"

    name = parts[-1]
    if CONSOLE_KEYS.fullmatch(name):
        return "console key file"
    if CONSOLE_CONTENT.search(name):
        return "console content archive"
    if CAPTURE_NAMES.fullmatch(name):
        return "emulator capture"
    return None


def scan_paths(paths: Iterable[str], source: str, *, archive: bool = False) -> bool:
    clean = True
    seen: set[str] = set()
    for name in paths:
        if archive and name in {".", "./"}:
            continue
        normalized = name.removeprefix("./").removesuffix("/") if archive else name
        casefolded = normalized.casefold()
        reason = rejection(casefolded.split("/"), archive)
        if archive:
            if reason is None and casefolded in seen:
                reason = "duplicate archive member"
            seen.add(casefolded)
        if reason is not None:
            print(f"{source}: {ascii(name)}: {reason}", file=sys.stderr)
            clean = False
    return clean


def archive_paths(path: Path) -> Iterator[str]:
    if path.name.casefold().endswith(".zip"):
        with zipfile.ZipFile(path) as archive:
            yield from (entry.orig_filename for entry in archive.infolist())
    elif path.name.casefold().endswith(".tar.gz"):
        with tarfile.open(path, "r|gz") as archive:
            yield from (entry.name for entry in archive)
    else:
        raise ValueError("expected .zip or .tar.gz")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    inputs = parser.add_mutually_exclusive_group(required=True)
    inputs.add_argument("--stdin0", action="store_true", help="read NUL-terminated paths from stdin")
    inputs.add_argument("--archives", nargs="+", type=Path, help="scan .zip or .tar.gz members")
    args = parser.parse_args()

    if args.stdin0:
        raw_paths = sys.stdin.buffer.read()
        if raw_paths and not raw_paths.endswith(b"\0"):
            print("Git paths: missing final NUL", file=sys.stderr)
            return 1
        paths = raw_paths.decode("utf-8", errors="surrogateescape").split("\0")[:-1]
        return int(not scan_paths(paths, "Git paths"))

    clean = True
    for archive in args.archives:
        try:
            if not scan_paths(archive_paths(archive), ascii(str(archive)), archive=True):
                clean = False
        except (OSError, EOFError, ValueError, zipfile.BadZipFile, tarfile.TarError, zlib.error) as error:
            print(f"{ascii(str(archive))}: cannot read archive: {ascii(str(error))}", file=sys.stderr)
            clean = False
    return int(not clean)


if __name__ == "__main__":
    sys.exit(main())
